#!/usr/bin/env python3
"""Turn the desktop menu's actions into Vicinae script commands.

    menu-commands.py

Every entry in quickshell/panels/menu.json that has an action becomes a
script command in Vicinae's script directory, so Alt+Space reaches the same
pickers and tools as the desktop menu (Super+Escape). Entries inside a
submenu are titled after it ("Screenshot: Region"). An entry's "when" test
runs when the command does; if it fails, Vicinae says what is missing.

The files are named dotfiles-<id>.sh and are plain output: edit menu.json and
run this again (reload-desktop.sh, Super+Ctrl+R, does). Commands whose entry
is gone are removed. Entries Vicinae has built in are left out: "Apps" (it is
the app launcher), and its own calculator, clipboard history, emoji picker,
file search, and web search shortcuts. So are the Wi-Fi, Bluetooth, and
Display panels, which Waybar's icons open directly.
"""

import json
import os
import shlex
from pathlib import Path

HOME = Path.home()
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config"))
DATA = Path(os.environ.get("XDG_DATA_HOME", HOME / ".local/share"))
MENU = CONFIG / "quickshell/panels/menu.json"
SCRIPTS = DATA / "vicinae/scripts"
PREFIX = "dotfiles-"
SKIP = {"apps", "tools.calculator", "tools.clipboard", "tools.emoji", "tools.files", "tools.web",
        "setup.network", "setup.bluetooth", "setup.display"}
ICON_THEMES = [Path("/usr/share/icons") / t for t in ("Papirus-Dark", "Papirus", "hicolor")]

# Icon theme names to try for each entry, best first. Entries without a match
# use their top-level category's icons.
ICONS = {
    "overview": ["preferences-system-windows", "view-grid"],
    "keybinds": ["preferences-desktop-keyboard-shortcuts", "preferences-desktop-keyboard"],
    "power": ["system-shutdown"],
    "capture": ["applets-screenshooter", "org.gnome.Screenshot"],
    "capture.record": ["simplescreenrecorder", "media-record"],
    "capture.ocr": ["gscan2pdf", "scanner"],
    "capture.colour": ["gcolor3", "color-picker", "preferences-color"],
    "style": ["preferences-desktop-theme"],
    "style.wallpaper": ["preferences-desktop-wallpaper"],
    "style.opacity": ["preferences-desktop-effects", "preferences-system-windows"],
    "style.bar": ["preferences-system-windows", "panel"],
    "style.reload": ["view-refresh", "system-reboot"],
    "setup": ["preferences-system"],
    "setup.network": ["preferences-system-network", "network-wireless"],
    "setup.bluetooth": ["bluetooth", "preferences-system-bluetooth"],
    "setup.audio": ["multimedia-volume-control", "pavucontrol"],
    "setup.display": ["preferences-desktop-display"],
    "setup.monitors": ["nwg-displays", "preferences-desktop-display"],
    "setup.night": ["redshift", "preferences-desktop-color"],
    "setup.idle": ["preferences-desktop-screensaver"],
    "setup.power": ["preferences-system-power", "battery"],
    "setup.defaults": ["preferences-desktop-default-applications"],
    "setup.packages": ["system-software-install", "octopi", "package-manager"],
    "setup.vm": ["virt-manager", "qemu"],
    "setup.fingerprint": ["fingerprint-gui", "preferences-desktop-user-password"],
    "setup.hyprland": ["hyprland", "preferences-system"],
    "tools": ["applications-utilities", "utilities-terminal"],
    "tools.clipboard": ["clipit", "edit-paste"],
    "tools.calculator": ["accessories-calculator"],
    "tools.emoji": ["preferences-desktop-emoticons", "face-smile"],
    "tools.agent": ["utilities-terminal"],
    "tools.notes": ["accessories-notes", "accessories-text-editor"],
    "tools.files": ["system-search", "system-file-manager"],
    "tools.web": ["web-browser"],
    "tools.transcode": ["handbrake", "multimedia-video-player"],
    "tools.monitor": ["utilities-system-monitor", "btop"],
}


def find_icon(name):
    for theme in ICON_THEMES:
        for size in ("64x64", "48x48", "scalable"):
            for ext in ("svg", "png"):
                for path in (theme / size).glob(f"*/{name}.{ext}"):
                    return path
    return None


def icon_for(entry_id):
    parts = entry_id.split(".")
    # The entry itself, then its parents up to the category.
    for depth in range(len(parts), 0, -1):
        for name in ICONS.get(".".join(parts[:depth]), []):
            path = find_icon(name)
            if path:
                return str(path)
    return None


def script(entry, title, category, prelude):
    keywords = entry.get("keywords", "").split()
    if category:
        keywords.append(category.lower())
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by ~/.config/vicinae/menu-commands.py from quickshell/panels/menu.json.",
        "# @vicinae.schemaVersion 1",
        f"# @vicinae.title {title}",
        "# @vicinae.mode silent",
    ]
    icon = icon_for(entry["id"])
    if icon:
        lines.append(f"# @vicinae.icon {icon}")
    if entry.get("description"):
        lines.append(f"# @vicinae.description {entry['description']}")
    if keywords:
        lines.append(f"# @vicinae.keywords {json.dumps(keywords)}")
    lines.append("")
    if entry.get("when"):
        test = prelude + "\n" + entry["when"]
        lines += [
            f"if ! bash -c {shlex.quote(test)} >/dev/null 2>&1; then",
            f"    echo {shlex.quote(title + ' is not available: ' + entry['when'])}",
            "    exit 0",
            "fi",
        ]
    # Detach, as the desktop menu does, so pickers outlive the script.
    command = prelude + "\n" + entry["action"]
    lines.append(f"setsid -f bash -c {shlex.quote(command)} >/dev/null 2>&1 </dev/null")
    return "\n".join(lines) + "\n"


def main():
    menu = json.loads(MENU.read_text())
    prelude = menu.get("prelude", "")
    labels = {e["id"]: e["label"] for e in menu["entries"]}

    SCRIPTS.mkdir(parents=True, exist_ok=True)
    written = set()
    for entry in menu["entries"]:
        if "action" not in entry or entry["id"] in SKIP:
            continue
        parts = entry["id"].split(".")
        # Top-level submenus (Capture, Style...) are categories; deeper ones
        # (Screenshot, Wallpaper) name their entries.
        parent = ".".join(parts[:-1])
        title = entry["label"]
        if len(parts) > 2:
            title = f"{labels[parent]}: {title}"
        category = labels.get(parts[0]) if len(parts) > 1 else None

        name = f"{PREFIX}{entry['id']}.sh"
        path = SCRIPTS / name
        path.write_text(script(entry, title, category, prelude))
        path.chmod(0o755)
        written.add(name)

    for stale in SCRIPTS.glob(f"{PREFIX}*.sh"):
        if stale.name not in written:
            stale.unlink()
    print(f"{len(written)} Vicinae commands in {SCRIPTS}")


if __name__ == "__main__":
    main()
