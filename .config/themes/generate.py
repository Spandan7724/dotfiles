def main():
    if len(sys.argv) < 2 or sys.argv[1] in ("-h", "--help"):
        print(__doc__.strip())
        sys.exit(0 if len(sys.argv) >= 2 else 2)

    theme_dir = THEMES / sys.argv[1]
    if not (theme_dir / "colors.toml").is_file():
        sys.exit(f"No colors.toml in {theme_dir}")
    p = load_palette(theme_dir)

    if "--extras" in sys.argv[2:]:
        for name, content in extra_files(p).items():
            (theme_dir / name).write_text(content)
        print(f"{theme_dir.name}: extras")
        return

    files = {
        "thunar.css": thunar_css(p),
        "quickshell.json": quickshell_json(p),
        "hyprland.lua": hyprland_lua(p),
        "helix.toml": helix_toml(p),
        **nvim_files(p),
        **doom_files(p),
        **extra_files(p),
    }
    if p["apps"].get("btop") != "keep":
        files["btop.theme"] = btop_theme(p)
    if "--all" in sys.argv[2:]:
        files.update(core_files(p))

    # Drop outputs a previous palette produced but this one does not.
    for stale in ("base46.lua", "doom-palette.el"):
        if stale not in files and (theme_dir / stale).exists():
            (theme_dir / stale).unlink()

    for name, content in files.items():
        (theme_dir / name).write_text(content)
    print(f"{theme_dir.name}: " + ", ".join(sorted(files)))


if __name__ == "__main__":
    main()
