def helix_syntax_lines(syn):
    lines = []
    for scope, (colour, mods) in HELIX_SYNTAX.items():
        mods = list(mods)
        if scope.startswith("keyword") and syn["bold_keywords"] and "bold" not in mods:
            mods.append("bold")
        if scope.startswith("function") and syn["bold_functions"] and "bold" not in mods:
            mods.append("bold")
        if scope == "string" and syn["italic_strings"]:
            mods.append("italic")
        parts = []
        if colour:
            parts.append(f'fg = "syn_{colour}"')
        if mods:
            parts.append("modifiers = [" + ", ".join(f'"{m}"' for m in mods) + "]")
        lines.append(f'"{scope}" = {{ {", ".join(parts)} }}')
    return "\n".join(lines)


