def hyprland_lua(p):
    if "hyprland_active_border" in p:
        parts = p["hyprland_active_border"].split()
        active = "{ colors = { " + ", ".join(f'"{c}"' for c in parts) + " }, angle = 45 }"
        inactive = f'"{p.get("hyprland_inactive_border", hypr_rgba(p["selection"]))}"'
    else:
        active = f'"{hypr_rgba(p["accent"], "ee")}"'
        inactive = f'"{hypr_rgba(p["selection"], "aa")}"'
    return f"""-- Window border colors for this theme; hyprland.lua loads this file.
-- Generated by themes/generate.py from colors.toml.
local active = {active}
local inactive = {inactive}

hl.config({{
    general = {{ col = {{ active_border = active, inactive_border = inactive }} }},
    group = {{ col = {{ border_active = active, border_inactive = inactive }} }},
}})
"""


def nvim_files(p):
    """nvim.lua names the NvChad (base46) theme; custom palettes get base46.lua,
    which nvim/lua/themes/dotfiles.lua loads."""
    builtin = p["apps"].get("nvchad")
    if builtin:
        return {"nvim.lua": f'-- NvChad (base46) theme for this theme; read by nvim/lua/chadrc.lua.\nreturn "{builtin}"\n'}

    bg, fg = p["background"], p["foreground"]
    syn = p["syntax"]
    step = lambda t: mix(bg, fg, t)
    base_30 = {
        "white": fg,
        "darker_black": p["dark_background"],
        "black": bg,
        "black2": step(0.04),
        "one_bg": step(0.07),
        "one_bg2": step(0.11),
        "one_bg3": step(0.15),
        "grey": step(0.22),
        "grey_fg": syn["comment"] if "comment" in p["syntax_set"] else step(0.28),
        "grey_fg2": step(0.34),
        "light_grey": step(0.42),
        "red": p["red"],
        "baby_pink": mix(p["red"], fg, 0.3),
        "pink": mix(p["red"], p["magenta"], 0.5),
        "line": step(0.10),
        "green": p["green"],
        "vibrant_green": mix(p["green"], fg, 0.25),
        "nord_blue": mix(p["blue"], p["cyan"], 0.4),
        "blue": p["blue"],
        "yellow": p["yellow"],
        "sun": mix(p["yellow"], fg, 0.25),
        "purple": p["magenta"],
        "dark_purple": mix(p["magenta"], bg, 0.15),
        "teal": mix(p["green"], p["cyan"], 0.5),
        "orange": p["orange"],
        "cyan": p["cyan"],
        "statusline_bg": step(0.03),
        "lightbg": step(0.10),
        "pmenu_bg": p["accent"],
        "folder_bg": p["blue"],
    }
    base_16 = {
        "base00": bg,
        "base01": step(0.05),
        "base02": step(0.10),
        "base03": step(0.30),
        "base04": step(0.55),
        "base05": fg,
        "base06": mix(fg, p["bright_foreground"], 0.5),
        "base07": p["bright_foreground"],
        "base08": syn["builtin"],
        "base09": syn["constant"],
        "base0A": syn["type"],
        "base0B": syn["string"],
        "base0C": syn["operator"],
        "base0D": syn["function"],
        "base0E": syn["keyword"],
        "base0F": syn["number"] if "number" in p["syntax_set"] else mix(p["red"], p["orange"], 0.5),
    }
    # Weight and slant for themes that separate tokens by more than colour.
    styles = []
    if syn["bold_keywords"]:
        styles += ['["@keyword"] = { bold = true }', '["@keyword.function"] = { bold = true }',
                   '["@keyword.return"] = { bold = true }', '["@keyword.import"] = { bold = true }',
                   '["@conditional"] = { bold = true }', '["@repeat"] = { bold = true }']
    if syn["bold_functions"]:
        styles += ['["@function"] = { bold = true }', '["@function.call"] = { bold = true }',
                   '["@function.method"] = { bold = true }', '["@function.method.call"] = { bold = true }']
    if syn["italic_comments"]:
        styles += ['["@comment"] = { italic = true }']
    if syn["italic_strings"]:
        styles += ['["@string"] = { italic = true }']
    polish = ""
    if styles:
        polish = "\nM.polish_hl = {\n    treesitter = {\n" + "".join(f"        {x},\n" for x in styles) + "    },\n}\n"
    lua_table = lambda d: "\n".join(f'    {k} = "{v}",' for k, v in d.items())
    return {
        "nvim.lua": '-- NvChad (base46) theme for this theme; read by nvim/lua/chadrc.lua.\nreturn "dotfiles"\n',
        "base46.lua": f"""-- base46 palette for this theme, loaded by nvim/lua/themes/dotfiles.lua.
-- Generated by themes/generate.py from colors.toml.
local M = {{}}

M.base_30 = {{
{lua_table(base_30)}
}}

M.base_16 = {{
{lua_table(base_16)}
}}

M.type = "{'dark' if p['dark'] else 'light'}"
{polish}
return M
""",
    }


def doom_files(p):
    """doom.el sets `doom-theme'; custom palettes get doom-palette.el, which
    doom/themes/doom-dotfiles-theme.el reads."""
    builtin = p["apps"].get("doom")
    if builtin:
        return {"doom.el": f";; Doom theme for this theme; loaded by doom/config.el.\n(setq doom-theme '{builtin})\n"}

    bg, fg = p["background"], p["foreground"]
    outer = p["dark_background"]
    colors = {
        "bg": bg,
        "bg-alt": outer,
        "base0": mix(outer, "#000000" if p["dark"] else "#ffffff", 0.3),
        "base1": mix(outer, bg, 0.3),
        "base2": mix(outer, bg, 0.6),
        "base3": mix(bg, fg, 0.06),
        "base4": mix(bg, fg, 0.2),
        "base5": mix(bg, fg, 0.38),
        "base6": mix(bg, fg, 0.55),
        "base7": mix(bg, fg, 0.72),
        "base8": p["bright_foreground"],
        "fg": fg,
        "fg-alt": p["muted"],
        "red": p["red"],
        "orange": p["orange"],
        "green": p["green"],
        "teal": mix(p["green"], p["cyan"], 0.5),
        "yellow": p["yellow"],
        "blue": p["blue"],
        "dark-blue": mix(p["blue"], bg, 0.3),
        "magenta": p["magenta"],
        "violet": mix(p["magenta"], p["blue"], 0.4),
        "cyan": p["cyan"],
        "dark-cyan": mix(p["cyan"], bg, 0.3),
        "accent": p["accent"],
        "selection": p["selection"],
    }
    syn = p["syntax"]
    for key in ("keyword", "function", "string", "type", "constant", "number",
                "builtin", "operator", "punctuation", "comment", "variable"):
        colors["syn-" + key] = syn[key]
    flags = "\n".join(f"(setq dotfiles-doom-{name.replace('_', '-')} {'t' if syn[name] else 'nil'})"
                      for name in ("bold_keywords", "bold_functions", "italic_comments", "italic_strings"))
    body = "\n".join(f'  ({k} . "{v}")' for k, v in colors.items())
    return {
        "doom.el": ";; Doom theme for this theme; loaded by doom/config.el.\n(setq doom-theme 'doom-dotfiles)\n",
        "doom-palette.el": f""";; Palette for doom/themes/doom-dotfiles-theme.el.
;; Generated by themes/generate.py from colors.toml.
(setq dotfiles-doom-dark {'t' if p['dark'] else 'nil'})
{flags}
(setq dotfiles-doom-palette
 '(
{body}))
""",
    }


