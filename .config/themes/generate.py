# ---- color helpers ------------------------------------------------------------

def rgb(hex_color):
    h = hex_color.lstrip("#")[:6]
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexc(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v))) for v in c)


def mix(a, b, t):
    """Blend from a (t=0) to b (t=1)."""
    ca, cb = rgb(a), rgb(b)
    return hexc(tuple(x + (y - x) * t for x, y in zip(ca, cb)))


def luminance(c):
    def channel(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (channel(v) for v in rgb(c))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def on_color(c):
    """Black or white, whichever has the higher contrast ratio on c."""
    lum = luminance(c)
    return "#000000" if (lum + 0.05) / 0.05 >= 1.05 / (lum + 0.05) else "#ffffff"


def rgba(c, alpha):
    r, g, b = rgb(c)
    return f"rgba({r}, {g}, {b}, {alpha})"


def hypr_rgba(c, alpha="ff"):
    return "rgba(" + c.lstrip("#")[:6] + alpha + ")"


# ---- palette ------------------------------------------------------------------

def load_palette(theme_dir):
    data = tomllib.loads((theme_dir / "colors.toml").read_text())
    p = {k: v for k, v in data.items() if isinstance(v, str)}
    p["apps"] = data.get("apps", {})
    dark = p.get("mode", "dark") == "dark"
    bg, fg = p["background"], p["foreground"]

    p.setdefault("dark_background", mix(bg, "#000000" if dark else "#ffffff", 0.2))
    p.setdefault("lighter_background", mix(bg, fg, 0.08))
    p.setdefault("selection", mix(bg, fg, 0.18))
    p.setdefault("light_foreground", fg)
    p.setdefault("bright_foreground", fg)
    p.setdefault("dark_foreground", p.get("muted", mix(bg, fg, 0.45)))
    p.setdefault("muted", p["dark_foreground"])
    p.setdefault("accent", p.get("blue", fg))
    p.setdefault("orange", p.get("yellow", p["red"]))
    for name in ("red", "green", "yellow", "blue", "magenta", "cyan"):
        p.setdefault("bright_" + name, p[name])
    # Status colours. Palettes may set them; otherwise the terminal colours
    # stand in.
    p.setdefault("error", p["red"])
    p.setdefault("warning", p["yellow"])
    p.setdefault("success", p["green"])
    p.setdefault("selection_background", p["selection"])
    p.setdefault("selection_foreground", p["bright_foreground"])
    p["on_accent"] = on_color(p["accent"])
    p["dark"] = dark

    # Editor syntax colours. Colourful palettes use their terminal colours;
    # greyscale ones (Solitude, Vantablack) set a [syntax] table instead, or
    # every token comes out a slightly different grey.
    syntax = {
        "keyword": p["magenta"],
        "function": p["blue"],
        "string": p["green"],
        "type": p["yellow"],
        "constant": p["orange"],
        "number": p["orange"],
        "builtin": p["red"],
        "operator": p["cyan"],
        "punctuation": p["muted"],
        "comment": p["muted"],
        "variable": fg,
        "bold_keywords": False,
        "bold_functions": False,
        "italic_comments": False,
        "italic_strings": False,
    }
    syntax.update(data.get("syntax", {}))
    p["syntax"] = syntax
    p["syntax_set"] = set(data.get("syntax", {}))
    return p


