#!/usr/bin/env bash
# Write ghostty/colors.ghostty from the palette kitty uses: Matugen's
# kitty/colors.conf, overridden by the current theme's kitty.conf (the same
# order kitty.conf includes them in). Then have running Ghostty windows reload.
# reload-apps.sh and wallpaper.sh run this; it is best effort.

set -u

config_root="${XDG_CONFIG_HOME:-$HOME/.config}"
out="$config_root/ghostty/colors.ghostty"

sources=()
for file in "$config_root/kitty/colors.conf" "$config_root/themes/current/kitty.conf"; do
    [[ -r "$file" ]] && sources+=("$file")
done

mkdir -p "$(dirname "$out")"
awk '
    $1 == "background"           { set("background", $2) }
    $1 == "foreground"           { set("foreground", $2) }
    $1 == "cursor"               { set("cursor-color", $2) }
    $1 == "cursor_text_color"    { set("cursor-text", $2) }
    $1 == "selection_background" { set("selection-background", $2) }
    $1 == "selection_foreground" { set("selection-foreground", $2) }
    $1 ~ /^color([0-9]|1[0-5])$/ { n = substr($1, 6); set("palette = " n, n "=" $2) }
    function set(key, value) {
        if (!(key in seen)) order[++count] = key
        seen[key] = 1
        values[key] = value
    }
    END {
        print "# Generated by themes/ghostty-colors.sh from the kitty palette; do not edit."
        for (i = 1; i <= count; i++) {
            key = order[i]
            if (key ~ /^palette/) print "palette = " values[key]
            else print key " = " values[key]
        }
    }
' "$config_root/kitty/colors.conf" "$config_root/themes/current/kitty.conf" 2>/dev/null >"$out.tmp" \
    && mv -f -- "$out.tmp" "$out"

# Ghostty reloads its configuration on SIGUSR2.
pkill -USR2 -x ghostty 2>/dev/null || true
exit 0
